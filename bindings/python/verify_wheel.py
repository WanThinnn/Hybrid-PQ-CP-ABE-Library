#!/usr/bin/env python3
"""Check native wheel contents, version and all three ABE schemes after install."""

import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import textwrap
import zipfile

from stage_native import REQUIRED_NOTICES

ROOT = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
EXTENSION = {"win32": "dll", "linux": "so", "darwin": "dylib"}[sys.platform]


def verify(wheel_path: Path):
    with zipfile.ZipFile(wheel_path) as archive:
        names = set(archive.namelist())
        lib_prefix = "pq_cp_abe/_libs/"
        required = {lib_prefix + f"libhybrid-pq-cp-abe.{EXTENSION}"}
        if EXTENSION == "dll":
            required.add(lib_prefix + "libcpabe_tkn20.dll")
        missing = required - names
        if missing:
            raise RuntimeError(f"Missing native runtimes: {sorted(missing)}")
        packaged_notices = {
            name.split(".dist-info/licenses/release-licenses/", 1)[1]
            for name in names if ".dist-info/licenses/release-licenses/" in name
        }
        if missing_notices := REQUIRED_NOTICES - packaged_notices:
            raise RuntimeError(f"Missing wheel license files: {sorted(missing_notices)}")
        if "pq_cp_abe/__init__.py" not in names:
            raise RuntimeError("Python SDK files missing")
        if "py3-none-any" in wheel_path.name:
            raise RuntimeError("Native wheels cannot be platform-independent")
        if any("__pycache__" in item or item.endswith(".pyc") for item in names):
            raise RuntimeError("Generated bytecode must not be included")

    with tempfile.TemporaryDirectory(prefix="pq-cp-abe-wheel-") as folder:
        target = Path(folder) / "installed"
        target.mkdir()
        subprocess.run([
            sys.executable, "-m", "pip", "install",
            "--no-index", "--no-deps", "--disable-pip-version-check",
            "--target", str(target), str(wheel_path.resolve())
        ], check=True)

        script = textwrap.dedent("""
            import os
            import sys
            from pathlib import Path
            from tempfile import TemporaryDirectory

            import pq_cp_abe as abe
            from pq_cp_abe._native import abe_lib, _lib_path

            expected_version = sys.argv[1]
            assert abe.__version__ == expected_version, (abe.__version__, expected_version)
            actual_native_version = abe_lib.getVersion().decode()
            assert actual_native_version == expected_version, (
                "Native binary mismatch", actual_native_version, expected_version
            )
            assert "_libs" in _lib_path.parts, _lib_path

            with TemporaryDirectory(prefix="abe-tests-") as tmp:
                directory = Path(tmp)
                schemes = (
                    ("AC17", abe.CPABE_SCHEME_AC17),
                    ("TKN20", abe.CPABE_SCHEME_TKN20),
                    ("CoverCrypt", abe.CPABE_SCHEME_COVERCRYPT),
                )
                for name, scheme in schemes:
                    subdir = directory / name
                    subdir.mkdir()
                    if name == "CoverCrypt":
                        config = subdir / "config.json"
                        config.write_text(
                            '{"dimensions":[{"name":"admin","attributes":["present","absent"]},'
                            '{"name":"it","attributes":["present","absent"]}]}',
                            encoding="utf-8",
                        )
                        os.environ["HCPABE_COVERCRYPT_CONFIG"] = str(config)
                        os.environ["HCPABE_COVERCRYPT_MODE"] = "hybridized"
                    else:
                        os.environ.pop("HCPABE_COVERCRYPT_CONFIG", None)
                        os.environ.pop("HCPABE_COVERCRYPT_MODE", None)

                    assert abe.call_setup_with_scheme(str(subdir), scheme) == abe.HCPABE_SUCCESS, name
                    master = subdir / "cpabe_msk.key"
                    public = subdir / "cpabe_pk.key"
                    private = subdir / "alice.key"
                    message = subdir / "input.txt"
                    cipher = subdir / "ciphertext.bin"
                    recovered = subdir / "recovered.txt"
                    message.write_bytes(b"pq-cp-abe isolated wheel test")
                    assert abe.call_generate_secret_key_with_scheme(
                        str(master), "admin it", str(private), scheme
                    ) == abe.HCPABE_SUCCESS, name
                    assert abe.call_hybrid_cpabe_encrypt_with_scheme(
                        str(public), str(message), "admin and it", str(cipher), scheme
                    ) == abe.HCPABE_SUCCESS, name
                    assert abe.call_hybrid_cpabe_decrypt(
                        str(private), str(cipher), str(recovered)
                    ) == abe.HCPABE_SUCCESS, name
                    assert recovered.read_bytes() == message.read_bytes(), name
                    print("PASS:", name)
            # Validate extended API from the installed wheel, not the source tree.
            key = bytes(range(32))
            iv = bytes(range(12))
            wrapped = abe.aes_gcm_encrypt(key, iv, b"binary payload", b"aad")
            assert abe.aes_gcm_decrypt(key, iv, wrapped, b"aad") == b"binary payload"
            public_sign, private_sign = abe.ml_dsa_87_generate_keypair()
            signature = abe.ml_dsa_87_sign(b"payload", private_sign)
            assert abe.ml_dsa_87_verify(b"payload", signature, public_sign)
            assert not abe.ml_dsa_87_verify(b"tampered", signature, public_sign)
            public_buffer, master_buffer = abe.setup_buffer(abe.CPABE_SCHEME_AC17)
            user_buffer = abe.genkey_buffer(master_buffer, "admin it", abe.CPABE_SCHEME_AC17)
            cipher_buffer = abe.call_hybrid_cpabe_encryptBuffer_with_scheme(
                public_buffer, b"buffer payload", "admin and it", abe.CPABE_SCHEME_AC17
            )
            assert abe.call_hybrid_cpabe_decryptBuffer(user_buffer, cipher_buffer) == b"buffer payload"
            print("PASS: AES-GCM, ML-DSA-87, buffer setup/genkey")
            print("Verified installed wheel and native version:", expected_version)
        """)
        env = os.environ.copy()
        env["PYTHONPATH"] = str(target)
        env["PYTHONNOUSERSITE"] = "1"
        subprocess.run(
            [sys.executable, "-s", "-c", script, VERSION],
            cwd=folder, env=env, check=True,
        )
        # The wheel itself must support the same full self-test, with no
        # imports or native library paths borrowed from the source checkout.
        subprocess.run(
            [sys.executable, "-s", "-m", "pq_cp_abe", "--test"],
            cwd=folder, env=env, check=True,
        )
    print(f"Verified: {wheel_path.name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel-dir", required=True, type=Path)
    args = parser.parse_args()
    wheels = sorted(args.wheel_dir.glob("*.whl"))
    if len(wheels) != 1:
        raise RuntimeError(f"Expected exactly one wheel, got {len(wheels)}: {wheels}")
    verify(wheels[0])


if __name__ == "__main__":
    main()
